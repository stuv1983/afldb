async function removeFixtureAuthUsers(emails: string[]): Promise<void> {
  if (emails.length === 0) return;
  const users = await sql<{ id: number; email: string }[]>`
    SELECT id, email FROM auth_users WHERE email = ANY(${emails})
  `;
  if (users.length === 0) {
    console.log('No matching fixture auth accounts found.');
    return;
  }
  const userIds = users.map((r) => r.id);
  const blocked = await blockedAuthReferences(userIds);
  if (blocked.length > 0) {
    const detail = blocked.map((b) => `${b.ref} (${b.n})`).join(', ');
    throw new Error(`Refusing to delete fixture auth accounts: still referenced by ${detail}.`);
  }
  await sql`DELETE FROM auth_audit_log WHERE actor_user_id = ANY(${userIds})`;
  await sql`DELETE FROM auth_sessions WHERE user_id = ANY(${userIds})`;
  await sql`DELETE FROM auth_users WHERE id = ANY(${userIds})`;
  console.log(`Removed ${users.length} fixture auth account(s): ${users.map((r) => r.email).join(', ')}`);
}

