    createdSeasons.push(BROWNLOW_SHORT_SEASON);

    const passwordHash = await hashPassword(password);
    for (const [role, email] of Object.entries(FIXTURE_EMAILS)) {
      const secret = generateTotpSecret();
      await sql`
        INSERT INTO auth_users (email, role, password_hash, totp_secret,
                                 must_change_password, password_changed_at, disabled_at)
        VALUES (${email}, ${role}, ${passwordHash}, ${secret}, false, now(), NULL)
        ON CONFLICT (email) DO UPDATE
          SET role = EXCLUDED.role, password_hash = EXCLUDED.password_hash,
              totp_secret = EXCLUDED.totp_secret, totp_last_step = NULL,
              must_change_password = false, password_changed_at = now(), disabled_at = NULL
      `;
      await sql`
        UPDATE auth_sessions SET revoked_at = now()
         WHERE user_id = (SELECT id FROM auth_users WHERE email = ${email}) AND revoked_at IS NULL
      `;
      createdEmails.push(email);
      console.log(`\n${role} ready: ${email}`);
      console.log('  ENROL THIS NOW (credential, shown once, terminal only):');
      console.log(`  TOTP secret : ${secret}`);
      console.log(`  otpauth URI : ${totpUri(secret, email)}`);
    }

    console.log('\n--- Fixture summary ---');
    console.log(`Main:  /admin/brownlow/${main.season}  matches: ${main.matches.map((m) => m.matchId).join(', ')}`
      + (main.wildcardFinalMatchId ? ` | wildcard final: ${main.wildcardFinalMatchId}` : '')
      + (main.grandFinalMatchId ? ` | grand final: ${main.grandFinalMatchId}` : ''));
    console.log(`Short: /admin/brownlow/${short.season}  matches: ${short.matches.map((m) => m.matchId).join(', ')}`
      + ' (second match has a short away lineup)');
    console.log('\nCREATE OK. Do not screenshot or log this terminal -- it carries one-time TOTP secrets.');
  } catch (error) {
    console.error('\nCREATE FAILED. Partial state before failure:');
    console.error(`  Seasons seeded: ${createdSeasons.length > 0 ? createdSeasons.join(', ') : '(none)'}`);
    console.error(`  Auth accounts created: ${createdEmails.length > 0 ? createdEmails.join(', ') : '(none)'}`);
    console.error('\nAttempting automatic rollback of exactly that partial state...');
    try {
      if (createdSeasons.length > 0) await removeFixtureBrownlowData(createdSeasons);
      if (createdEmails.length > 0) await removeFixtureAuthUsers(createdEmails);
      console.error('Rollback complete: afldb_test has no fixture residue from this failed run.');
    } catch (rollbackError) {
      console.error('ROLLBACK ALSO FAILED -- manual cleanup required. Rollback error:');
      console.error(rollbackError);
      console.error('Re-run this fixture runner with "cleanup" once the underlying issue above is resolved.');
    }
    console.error('\nOriginal CREATE error:');
    throw error;
  }
}

async function cleanup(): Promise<void> {
  await assertAfldbTest();
  await removeFixtureBrownlowData([BROWNLOW_MAIN_SEASON, BROWNLOW_SHORT_SEASON]);
  await removeFixtureAuthUsers(Object.values(FIXTURE_EMAILS));
}

/**
 * READ-ONLY. Reports whether any ISSUE-155 fixture residue already exists
 * for the given seasons -- a seasons row, any matches on the fixture's
 * match_key prefix, or any players on its slug prefix. Exit code only:
 * 0 = clean, 2 = residue found, never writes anything. Called by CREATE
 * before it ever prompts for a password, so a stale run from a previous
 * interrupted attempt is caught before any new work starts, and
 * seedBrownlowSeason's own collision guard is never relied on to surface
 * this as a mid-run failure.
 */
async function checkResidue(seasons: number[]): Promise<boolean> {
  await assertAfldbTest();
  let residueFound = false;
  for (const season of seasons) {
    const prefix = `issue155-${season}-`;
    const [seasonRow] = await sql<{ year: number }[]>`SELECT year FROM seasons WHERE year = ${season}`;
    const [matchCount] = await sql<{ n: number }[]>`
      SELECT count(*)::int AS n FROM matches WHERE match_key LIKE ${`${prefix}%`}
    `;
    const [playerCount] = await sql<{ n: number }[]>`
      SELECT count(*)::int AS n FROM players WHERE slug LIKE ${`${prefix}%`}
    `;
    const hasResidue = !!seasonRow || matchCount.n > 0 || playerCount.n > 0;
    if (hasResidue) {
      residueFound = true;
      console.log(
        `Residue for season ${season}: seasons row=${!!seasonRow}, `
        + `matches=${matchCount.n}, players=${playerCount.n}`,
      );
    }
  }
  return residueFound;
}

