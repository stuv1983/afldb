/**
 * Ordered removal of disposable Brownlow rows for the given fixture seasons
 * only. Builds the fixture's own match id / player id sets explicitly BEFORE
 * any destructive delete, and uses them to scope every data_edits delete by
 * proven (table_name, row_id) membership -- the only two table_name values
 * a Brownlow/Match Sheet acceptance flow can write against fixture matches
 * are 'matches' and 'brownlow_vote_entry_state', both keyed by match_id;
 * 'brownlow_season_authority' is keyed by season; 'players' is included
 * defensively in case a fixture player's own row was edited via the data
 * editor during acceptance.
 */
async function removeFixtureBrownlowData(seasons: number[]): Promise<void> {
  for (const season of seasons) {
    const prefix = `issue155-${season}-`;

    const matchRows = await sql<{ id: number }[]>`
      SELECT id::int AS id FROM matches WHERE match_key LIKE ${`${prefix}%`}
    `;
    const matchIds = matchRows.map((r) => r.id);

    const playerRows = await sql<{ id: number }[]>`
      SELECT id::int AS id FROM players WHERE slug LIKE ${`${prefix}%`}
    `;
    const playerIds = playerRows.map((r) => r.id);

    if (matchIds.length > 0) {
      await sql`DELETE FROM data_edits WHERE table_name = 'matches' AND row_id = ANY(${matchIds})`;
      await sql`DELETE FROM data_edits WHERE table_name = 'brownlow_vote_entry_state' AND row_id = ANY(${matchIds})`;
      await sql`DELETE FROM brownlow_vote_entry_state WHERE match_id = ANY(${matchIds})`;
    }
    await sql`DELETE FROM data_edits WHERE table_name = 'brownlow_season_authority' AND row_id = ${season}`;
    await sql`DELETE FROM brownlow_season_authority WHERE season = ${season}`;
    await sql`DELETE FROM brownlow_round_votes WHERE season = ${season}`;
    await sql`DELETE FROM brownlow_season_votes WHERE season = ${season}`;

    if (playerIds.length > 0) {
      await sql`DELETE FROM data_edits WHERE table_name = 'players' AND row_id = ANY(${playerIds})`;
      await sql`DELETE FROM player_match_stats WHERE player_id = ANY(${playerIds})`;
      await sql`DELETE FROM player_career_stats WHERE player_id = ANY(${playerIds})`;
      await sql`DELETE FROM player_season_stats WHERE player_id = ANY(${playerIds})`;
      await sql`DELETE FROM player_club_season_stats WHERE player_id = ANY(${playerIds})`;
      await sql`DELETE FROM player_clubs WHERE player_id = ANY(${playerIds})`;
      await sql`DELETE FROM players WHERE id = ANY(${playerIds})`;
    }
    await sql`DELETE FROM club_seasons WHERE season = ${season}`;
    await sql`DELETE FROM matches WHERE match_key LIKE ${`${prefix}%`}`;
    await sql`DELETE FROM stat_availability WHERE season = ${season}`;
    await sql`DELETE FROM seasons WHERE year = ${season}`;
    console.log(`Removed fixture Brownlow data for season ${season}: ${matchIds.length} match(es), ${playerIds.length} player(s).`);
