// SIMULATION ONLY. Writes the simulated production checkout's credential file (.env, mode 600) and the simulation profile from the LIVE simulated cluster,
// so every identity the wrapper compares is read from the thing being simulated rather than typed. It never prints a credential.
// Env: SIM_ROLES (roles.json path), SIM_PORT, SIM_DB, SIM_ENV_OUT, SIM_PROFILE_OUT, SIM_ROOT, SIM_PROD_CHECKOUT, SIM_NODE, SIM_PYTHON, SIM_PGBIN, SIM_SSH_HOST.
import { readFileSync, writeFileSync } from 'node:fs';
import postgres from 'postgres';

const e = process.env;
for (const k of ['SIM_ROLES', 'SIM_PORT', 'SIM_DB', 'SIM_ENV_OUT', 'SIM_PROFILE_OUT', 'SIM_ROOT', 'SIM_PROD_CHECKOUT', 'SIM_NODE', 'SIM_PYTHON', 'SIM_PGBIN', 'SIM_SSH_HOST']) if (!e[k]) throw new Error(`${k} required`);
if (/^afldb_v2_.*_test$/.test(e.SIM_DB)) throw new Error('a simulated PRODUCTION database must not carry an isolated-test name (the stage tools refuse that in production mode)');
const roles = JSON.parse(readFileSync(e.SIM_ROLES, 'utf8'));
const dsn = (role) => `postgres://${role}:${encodeURIComponent(roles[role])}@127.0.0.1:${e.SIM_PORT}/${e.SIM_DB}`;

writeFileSync(e.SIM_ENV_OUT, `AFLDB_BACKUP_DATABASE_URL=${dsn('afldb_backup')}\nAFLDB_IMPORT_DATABASE_URL=${dsn('afldb_import')}\nAFLDB_AUTH_DATABASE_URL=${dsn('afldb_auth')}\n`, { flag: 'wx', mode: 0o600 });

const sql = postgres(dsn('afldb_backup'), { max: 1, connect_timeout: 8, onnotice: () => {} });
try {
  const [id] = await sql`SELECT current_database() AS db, (SELECT oid::text FROM pg_database WHERE datname = current_database()) AS oid,
    (SELECT system_identifier::text FROM pg_control_system()) AS sysid, current_setting('cluster_name') AS cluster,
    (SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname = current_database()) AS owner`;
  const ledger = await sql`SELECT name FROM afldb_meta.schema_migrations ORDER BY name COLLATE "C"`;
  const [ext] = await sql`SELECT string_agg(extname || '=' || extversion, ' ' ORDER BY extname) AS ext FROM pg_extension`;
  const lines = [
    '# V2-GAP-029 wrapper profile: SIMULATION of the production host on an isolated cluster. GENERATED by sim-env.mjs from the live simulated cluster.',
    'PROFILE_NAME="sim"', 'EVIDENCE_CLASS="SIMULATION"', 'EXPECT_HOST="streamanator"', 'EXPECT_USER="arm"',
    `PROD_CHECKOUT="${e.SIM_PROD_CHECKOUT}"`, `OPS_ROOT="${e.SIM_ROOT}/ops"`, `BACKUP_ROOT="${e.SIM_ROOT}/backups"`,
    `PGBIN="${e.SIM_PGBIN}"`, `NODE="${e.SIM_NODE}"`, `PYTHON="${e.SIM_PYTHON}"`,
    `EXPECT_SYSID="${id.sysid}"`, `EXPECT_OID="${id.oid}"`, `EXPECT_CLUSTER="${id.cluster}"`, `EXPECT_DB="${id.db}"`, 'EXPECT_DB_HOST="127.0.0.1"', `EXPECT_DB_PORT="${e.SIM_PORT}"`,
    `EXPECT_LEDGER_ROWS="${ledger.length}"`, `EXPECT_LEDGER_LAST="${ledger[ledger.length - 1].name}"`, `EXPECT_EXT="${ext.ext}"`, `EXPECT_DB_OWNER="${id.owner}"`,
    'WRITER_UNITS="afldb-sim-writer-nonexistent.service"', 'ALL_UNITS="afldb-sim-writer-nonexistent.service afldb-sim-timer-nonexistent.timer"', 'TIMER_UNIT="afldb-sim-timer-nonexistent.timer"',
    `SSH_HOST="${e.SIM_SSH_HOST}"`, '',
  ];
  writeFileSync(e.SIM_PROFILE_OUT, lines.join('\n'), { flag: 'wx', mode: 0o600 });
  console.log(`sim profile written: db=${id.db} oid=${id.oid} system=${id.sysid} cluster=${id.cluster} ledger=${ledger.length}/${ledger[ledger.length - 1].name} ext=${ext.ext}`);
} finally { await sql.end({ timeout: 5 }); }
